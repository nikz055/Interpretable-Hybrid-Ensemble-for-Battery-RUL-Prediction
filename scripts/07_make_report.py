"""Step 7: tables (CSV + Markdown) and figures from the saved predictions.

Everything here is computed from files written by steps 2-6; nothing is
re-trained. Outputs: results/tables/*.csv, results/figures/*.png, results/REPORT.md
"""
from __future__ import annotations

import argparse
import json
import sys
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from batteryrul.config import load_config, repo_path  # noqa: E402
from batteryrul.metrics import (bootstrap_ci, life_groups, paired_comparison,  # noqa: E402
                                regression_metrics, tertile_edges)

warnings.filterwarnings("ignore")

PRETTY = {
    "dummy": "Dummy (train mean, log space)", "ridge": "Ridge", "plsr": "PLSR",
    "rf": "Random forest", "xgb": "XGBoost", "mlp": "MLP",
    "mean_rf_xgb_mlp": "Equal-weight RF+XGB+MLP", "mean_rf_xgb": "Equal-weight RF+XGB",
    "valweighted_rf_xgb_mlp": "Validation-weighted RF+XGB+MLP",
    "stack_rf_xgb": "Stack RF+XGB", "stack_rf_mlp": "Stack RF+MLP", "stack_xgb_mlp": "Stack XGB+MLP",
    "stack_rf_xgb_mlp": "Stack RF+XGB+MLP (proposed)",
    "stack_ridge_rf_xgb_mlp": "Stack Ridge+RF+XGB+MLP (exploratory)",
}
MAIN_ORDER = ["dummy", "ridge", "plsr", "rf", "xgb", "mlp", "mean_rf_xgb_mlp",
              "valweighted_rf_xgb_mlp", "stack_rf_xgb_mlp", "stack_ridge_rf_xgb_mlp"]
ABL_ORDER = ["rf", "xgb", "mlp", "stack_rf_xgb", "stack_rf_mlp", "stack_xgb_mlp", "stack_rf_xgb_mlp",
             "mean_rf_xgb", "mean_rf_xgb_mlp", "valweighted_rf_xgb_mlp", "stack_ridge_rf_xgb_mlp"]


def pm(m, s, d=1):
    return f"{m:.{d}f} ± {s:.{d}f}" if np.isfinite(s) and s > 0 else f"{m:.{d}f}"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def pred_matrix(preds, model, part="test"):
    g = preds[(preds.model == model) & (preds.partition == part)]
    P = g.pivot(index="seed", columns="cell_id", values="y_pred")
    y = g.drop_duplicates("cell_id").set_index("cell_id").y_true
    return P, y.loc[P.columns]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    res = repo_path(cfg["output"]["results_dir"])
    tabs, figs = res / "tables", res / "figures"
    tabs.mkdir(parents=True, exist_ok=True)
    figs.mkdir(parents=True, exist_ok=True)
    main_cfg = json.loads((res / "runs" / "main.json").read_text())
    tag, final = main_cfg["tag"], main_cfg["final_ensemble"]
    run = res / "runs" / tag
    preds = pd.read_csv(run / "predictions.csv")
    summ = pd.read_csv(run / "metrics_summary.csv")
    sel = json.loads((run / "selection.json").read_text())
    best_ind = sel["best_individual_by_cv"]
    report = [f"# Results report (auto-generated by `scripts/07_make_report.py`)\n",
              f"Main configuration: feature set **{main_cfg['feature_set']}**, horizon **T = {main_cfg['horizon']}**, "
              f"selected by {main_cfg['selection_rule']} "
              f"(CV RMSE by set: {', '.join(f'{k}: {v:.1f}' for k, v in main_cfg['cv_rmse_final_ensemble_by_set'].items())}).",
              f"Best individual model (by training CV): **{best_ind}**. Final ensemble (by training CV): **{final}**.",
              "Test = 42 locked BatteryML MATR-1 test cells; mean ± std over 10 seeds; 95 % CI = cell bootstrap "
              "of the seed-averaged RMSE. CV RMSE = grouped 5-fold OOF RMSE on the 41 training cells "
              "(stacks: cross-fitted).\n"]

    # ---------- Table 1: BatteryML reproduction ----------
    bml = pd.read_csv(tabs / "batteryml_reproduction.csv")
    t1 = pd.DataFrame({"Model": bml.model, "Features": bml.features,
                       "Our RMSE": [pm(a, b) if np.isfinite(a) else "-" for a, b in zip(bml.RMSE, bml.RMSE_std.fillna(0))],
                       "BatteryML published": bml.batteryml_published_RMSE})
    t1.to_csv(tabs / "table1_batteryml_reproduction.csv", index=False)
    report += ["## Table 1 - BatteryML MATR-1 baselines re-run with this pipeline\n", md_table(t1), ""]

    # ---------- Table 2: main benchmark ----------
    bml_pred = pd.read_csv(res / "predictions" / "batteryml_baselines.csv").set_index("cell_id")
    test_s = summ[summ.partition == "test"].set_index("model")
    oof_s = summ[summ.partition == "oof"].set_index("model")
    rows = []
    for name in ["Variance model", "PLSR (QdLinear)"]:
        y = bml_pred.y_true.to_numpy()
        m = regression_metrics(y, bml_pred[name].to_numpy())
        lo, hi = bootstrap_ci(y, bml_pred[name].to_numpy()[None])
        rows.append({"Model": f"BatteryML {name}", "RMSE": f"{m['RMSE']:.1f}", "95% CI": f"[{lo:.0f}, {hi:.0f}]",
                     "MAE": f"{m['MAE']:.1f}", "MedAE": f"{m['MedAE']:.1f}", "R2": f"{m['R2']:.3f}",
                     "Bias": f"{m['Bias']:+.1f}", "nRMSE": f"{m['nRMSE']:.3f}", "MAPE %": f"{100 * m['MAPE']:.1f}",
                     "CV RMSE": "-"})
    for name in MAIN_ORDER:
        if name not in test_s.index:
            continue
        r = test_s.loc[name]
        P, y = pred_matrix(preds, name)
        lo, hi = bootstrap_ci(y.to_numpy(), P.to_numpy())
        rows.append({"Model": PRETTY.get(name, name) + (" ★" if name == final else ""),
                     "RMSE": pm(r.RMSE_mean, r.RMSE_std), "95% CI": f"[{lo:.0f}, {hi:.0f}]",
                     "MAE": pm(r.MAE_mean, r.MAE_std), "MedAE": pm(r.MedAE_mean, r.MedAE_std),
                     "R2": f"{r.R2_mean:.3f}", "Bias": f"{r.Bias_mean:+.1f}", "nRMSE": f"{r.nRMSE_mean:.3f}",
                     "MAPE %": f"{100 * r.MAPE_mean:.1f}", "CV RMSE": pm(oof_s.loc[name, "RMSE_mean"], oof_s.loc[name, "RMSE_std"])})
    t2 = pd.DataFrame(rows)
    t2.to_csv(tabs / "table2_main_benchmark.csv", index=False)
    report += ["## Table 2 - Experiment 1: main benchmark (test set)\n",
               "★ = final ensemble selected by training CV. BatteryML rows use their own features (single deterministic run).\n",
               md_table(t2), ""]

    # ---------- Table 3: paired comparisons ----------
    Pf, y = pred_matrix(preds, final)
    comp_rows = []
    for other in [best_ind, "ridge", "plsr", "rf", "xgb", "mlp", "mean_rf_xgb_mlp", "valweighted_rf_xgb_mlp"]:
        if other == final:
            continue
        Po, _ = pred_matrix(preds, other)
        c = paired_comparison(y.to_numpy(), Pf.to_numpy(), Po[Pf.columns].to_numpy())
        comp_rows.append({"Final ensemble vs": PRETTY.get(other, other) + (" (best individual, CV)" if other == best_ind else ""),
                          "ΔRMSE": f"{c['dRMSE']:+.1f}", "95% CI": f"[{c['dRMSE_lo']:+.1f}, {c['dRMSE_hi']:+.1f}]",
                          "P(ΔRMSE<0)": f"{c['P(dRMSE<0)']:.2f}", "ΔMAE": f"{c['dMAE']:+.1f}",
                          "Wilcoxon p (|err|)": f"{c['wilcoxon_p']:.3f}",
                          "cells better": f"{c['cells_A_better']}/{c['n_cells']}"})
    comp_rows = list({r["Final ensemble vs"]: r for r in comp_rows}.values())
    t3 = pd.DataFrame(comp_rows)
    t3.to_csv(tabs / "table3_paired_comparisons.csv", index=False)
    report += ["## Table 3 - Paired test-set comparisons of the final ensemble\n",
               "ΔRMSE < 0 favours the final ensemble. CI = paired cell bootstrap (2000 resamples) of the "
               "seed-averaged RMSE difference; Wilcoxon on seed-averaged per-cell absolute errors.\n",
               md_table(t3), ""]

    # ---------- Table 4: feature ablation ----------
    fa_rows = []
    for fs in cfg["experiments"]["main"]["feature_sets"]:
        rd = res / "runs" / f"T{main_cfg['horizon']}_{fs}"
        s = pd.read_csv(rd / "metrics_summary.csv")
        sl = json.loads((rd / "selection.json").read_text())
        te, oo = s[s.partition == "test"].set_index("model"), s[s.partition == "oof"].set_index("model")
        nfeat = len(pd.read_csv(res / "features" / f"features_{fs}_T{main_cfg['horizon']}.csv", nrows=1).columns) - 3
        for role, name in [("best individual (CV)", sl["best_individual_by_cv"]), ("final ensemble (CV)", sl["final_ensemble_by_cv"]),
                           ("RF", "rf"), ("XGBoost", "xgb"), ("Ridge", "ridge")]:
            fa_rows.append({"Feature set": fs, "#features": nfeat, "Role": role, "Model": name,
                            "Test RMSE": pm(te.loc[name, "RMSE_mean"], te.loc[name, "RMSE_std"]),
                            "Test MAE": pm(te.loc[name, "MAE_mean"], te.loc[name, "MAE_std"]),
                            "CV RMSE": pm(oo.loc[name, "RMSE_mean"], oo.loc[name, "RMSE_std"])})
    t4 = pd.DataFrame(fa_rows)
    t4.to_csv(tabs / "table4_feature_ablation.csv", index=False)
    report += ["## Table 4 - Experiment 2: feature ablation (T = 100)\n", md_table(t4), ""]

    # ---------- Table 5: ensemble ablation ----------
    w = pd.read_csv(run / "ensemble_weights.csv")
    wmean = w.groupby("combiner").mean(numeric_only=True)
    ea_rows = []
    for name in ABL_ORDER:
        if name not in test_s.index:
            continue
        wt = ""
        if name in wmean.index:
            ww = wmean.loc[name].drop(labels=["seed"], errors="ignore").dropna()
            wt = ", ".join(f"{k}={v:.2f}" for k, v in ww.items() if k != "intercept")
            if "intercept" in ww and name.startswith("stack"):
                wt += f", b={ww['intercept']:+.0f}"
        ea_rows.append({"Model": PRETTY.get(name, name), "Test RMSE": pm(test_s.loc[name, "RMSE_mean"], test_s.loc[name, "RMSE_std"]),
                        "Test MAE": pm(test_s.loc[name, "MAE_mean"], test_s.loc[name, "MAE_std"]),
                        "CV RMSE": pm(oof_s.loc[name, "RMSE_mean"], oof_s.loc[name, "RMSE_std"]),
                        "mean weights (OOF-fitted)": wt})
    t5 = pd.DataFrame(ea_rows)
    t5.to_csv(tabs / "table5_ensemble_ablation.csv", index=False)
    # complementarity: correlation of OOF errors
    errs = {}
    for m in ["ridge", "rf", "xgb", "mlp"]:
        P, yy = pred_matrix(preds, m, "oof")
        errs[m] = (P.mean(0) - yy).to_numpy()
    ecorr = pd.DataFrame(errs).corr().round(3)
    ecorr.to_csv(tabs / "table5b_oof_error_correlation.csv")
    report += ["## Table 5 - Experiment 3: ensemble ablation (main configuration)\n", md_table(t5), "",
               "OOF residual correlation between base models (seed-averaged; lower = more complementary):\n",
               md_table(ecorr.reset_index().rename(columns={"index": "model"})), ""]

    # ---------- Table 6: horizon ablation ----------
    hz_rows = []
    for T in cfg["experiments"]["horizon_ablation"]["horizons"]:
        rd = res / "runs" / f"T{T}_{main_cfg['feature_set']}"
        if not rd.exists():
            continue
        s = pd.read_csv(rd / "metrics_summary.csv")
        sl = json.loads((rd / "selection.json").read_text())
        te, oo = s[s.partition == "test"].set_index("model"), s[s.partition == "oof"].set_index("model")
        for role, name in [("dummy", "dummy"), ("best individual (CV)", sl["best_individual_by_cv"]),
                           ("final ensemble (CV)", sl["final_ensemble_by_cv"]), ("proposed stack", "stack_rf_xgb_mlp")]:
            hz_rows.append({"T": T, "Role": role, "Model": name,
                            "Test RMSE": pm(te.loc[name, "RMSE_mean"], te.loc[name, "RMSE_std"]),
                            "Test MAE": pm(te.loc[name, "MAE_mean"], te.loc[name, "MAE_std"]),
                            "CV RMSE": pm(oo.loc[name, "RMSE_mean"], oo.loc[name, "RMSE_std"]),
                            "_rmse": te.loc[name, "RMSE_mean"], "_std": te.loc[name, "RMSE_std"]})
    hz = pd.DataFrame(hz_rows)
    hz.drop(columns=["_rmse", "_std"]).to_csv(tabs / "table6_horizon_ablation.csv", index=False)
    report += [f"## Table 6 - Experiment 4: early-life horizon (feature set {main_cfg['feature_set']})\n",
               md_table(hz.drop(columns=["_rmse", "_std"])), ""]

    # ---------- Table 7: robustness ----------
    rob_path = res / "runs" / "robustness" / "robustness_summary.csv"
    if rob_path.exists():
        rob = pd.read_csv(rob_path)
        rob["cell"] = [f"{a:+.1f} ± {b:.1f}" for a, b in zip(rob.dRMSE_mean, rob.dRMSE_std.fillna(0))]
        t7 = rob[rob.condition != "clean"].pivot(index="model", columns="condition", values="cell")
        clean = rob[rob.condition == "clean"].set_index("model").RMSE_mean.round(1).rename("clean RMSE")
        t7 = pd.concat([clean, t7], axis=1).reset_index().rename(columns={"index": "model"})
        t7.to_csv(tabs / "table7_robustness_dRMSE.csv", index=False)
        robm = rob.copy()
        robm["cell"] = [f"{a:+.1f} ± {b:.1f}" for a, b in zip(robm.dMAE_mean, robm.dMAE_std.fillna(0))]
        t7b = robm[robm.condition != "clean"].pivot(index="model", columns="condition", values="cell").reset_index()
        t7b.to_csv(tabs / "table7b_robustness_dMAE.csv", index=False)
        report += ["## Table 7 - Experiment 5: robustness, ΔRMSE vs clean test input (mean ± std over seeds × repeats)\n",
                   md_table(t7), "", "ΔMAE:\n", md_table(t7b), ""]

    # ---------- Table 8: life groups ----------
    edges = tertile_edges(preds[(preds.partition == "oof")].drop_duplicates("cell_id").y_true)
    lg_rows = []
    for name in ["ridge", "rf", "xgb", "mlp", "mean_rf_xgb_mlp", final]:
        P, yy = pred_matrix(preds, name)
        g = life_groups(yy.to_numpy(), edges)
        e = P.mean(0).to_numpy() - yy.to_numpy()
        for grp in ("short", "medium", "long"):
            m = g == grp
            lg_rows.append({"Model": PRETTY.get(name, name), "Group": grp, "n": int(m.sum()),
                            "RMSE": f"{np.sqrt(np.mean(e[m] ** 2)):.1f}", "MAE": f"{np.mean(np.abs(e[m])):.1f}",
                            "Bias": f"{np.mean(e[m]):+.1f}"})
    t8 = pd.DataFrame(lg_rows).drop_duplicates()
    t8.to_csv(tabs / "table8_life_groups.csv", index=False)
    report += [f"## Table 8 - Errors by life group (tertiles of training labels: ≤{edges[0]:.0f}, ≤{edges[1]:.0f}, >{edges[1]:.0f} cycles; seed-averaged predictions)\n",
               md_table(t8), ""]

    # ---------- per-cell predictions (seed-averaged) ----------
    pc = {"cell_id": y.index, "y_true": y.values}
    for name in MAIN_ORDER:
        if name in test_s.index:
            P, _ = pred_matrix(preds, name)
            pc[name] = P[y.index].mean(0).round(1).values
    for name in ["Variance model", "PLSR (QdLinear)"]:
        pc[f"batteryml_{name}"] = bml_pred.loc[y.index, name].round(1).values
    pd.DataFrame(pc).to_csv(res / "predictions" / "test_predictions_main_seed_avg.csv", index=False)

    # ---------- figures ----------
    fig, axes = plt.subplots(1, 2, figsize=(11, 5))
    for ax, name in zip(axes, [best_ind, final]):
        P, yy = pred_matrix(preds, name)
        p, s = P.mean(0), P.std(0)
        ax.errorbar(yy, p[yy.index], yerr=s[yy.index], fmt="o", ms=4, alpha=0.8, ecolor="grey")
        lim = [0, max(yy.max(), p.max()) * 1.05]
        ax.plot(lim, lim, "k--", lw=1)
        r = test_s.loc[name]
        ax.set_title(f"{PRETTY.get(name, name)}\nRMSE {r.RMSE_mean:.0f}, MAE {r.MAE_mean:.0f} cycles")
        ax.set_xlabel("True cycle life")
        ax.set_ylabel("Predicted cycle life (mean ± sd over seeds)")
    fig.tight_layout()
    fig.savefig(figs / "pred_vs_true.png", dpi=150)
    plt.close(fig)

    order = [n for n in MAIN_ORDER if n in test_s.index and n != "dummy"]
    fig, ax = plt.subplots(figsize=(10, 4.5))
    xs = np.arange(len(order))
    ax.bar(xs - 0.2, test_s.loc[order, "RMSE_mean"], 0.4, yerr=test_s.loc[order, "RMSE_std"], label="test RMSE", capsize=3)
    ax.bar(xs + 0.2, oof_s.loc[order, "RMSE_mean"], 0.4, yerr=oof_s.loc[order, "RMSE_std"], label="training CV RMSE", capsize=3)
    ax.set_xticks(xs, [PRETTY.get(n, n).replace(" (", "\n(") for n in order], rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("RMSE (cycles)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(figs / "model_comparison.png", dpi=150)
    plt.close(fig)

    if len(hz):
        fig, ax = plt.subplots(figsize=(6, 4))
        for role in ["best individual (CV)", "final ensemble (CV)", "proposed stack", "dummy"]:
            h = hz[hz.Role == role]
            ax.errorbar(h["T"], h["_rmse"], yerr=h["_std"], marker="o", capsize=3, label=role)
        ax.set_xlabel("Observation horizon T (cycles)")
        ax.set_ylabel("Test RMSE (cycles)")
        ax.legend()
        fig.tight_layout()
        fig.savefig(figs / "horizon_ablation.png", dpi=150)
        plt.close(fig)

    if rob_path.exists():
        rob = pd.read_csv(rob_path)
        sub = rob[(rob.condition != "clean") & rob.model.isin(["ridge", "rf", "xgb", "mlp", final, "mean_rf_xgb_mlp"])]
        piv = sub.pivot(index="condition", columns="model", values="dRMSE_mean")
        err = sub.pivot(index="condition", columns="model", values="dRMSE_std")
        ax = piv.plot.bar(yerr=err, figsize=(9, 4.5), capsize=2)
        ax.set_ylabel("ΔRMSE vs clean (cycles)")
        ax.axhline(0, color="k", lw=0.6)
        plt.xticks(rotation=0)
        plt.tight_layout()
        plt.savefig(figs / "robustness.png", dpi=150)
        plt.close()

    fig, ax = plt.subplots(figsize=(9, 4.5))
    names = ["ridge", "rf", "xgb", "mlp", final]
    data = []
    for name in names:
        P, yy = pred_matrix(preds, name)
        data.append((P.mean(0) - yy).to_numpy())
    ax.boxplot(data, labels=[PRETTY.get(n, n).replace(" (", "\n(") for n in names], showfliers=True)
    ax.axhline(0, color="k", lw=0.6)
    ax.set_ylabel("Signed error, pred - true (cycles)")
    fig.tight_layout()
    fig.savefig(figs / "per_cell_error_distribution.png", dpi=150)
    plt.close(fig)

    # SHAP section
    sp = res / "runs" / "shap"
    if (sp / "plausibility.csv").exists():
        pl = pd.read_csv(sp / "plausibility.csv")
        cols = ["feature", "ensemble_share", "rf_share", "xgb_share", "mlp_share", "learned_sign",
                "expected_sign", "plausibility", "min_top10_frequency_rf_xgb", "stable"]
        pl = pl[cols].round(3)
        report += ["## SHAP - top-10 features of the final ensemble (held-out test cells)\n",
                   "share = fraction of total mean |SHAP|; learned sign = sign of Spearman(feature, SHAP); "
                   "stability = min over RF/XGB of the fraction of 15 runs (10 seeds + 5 folds) in which the feature is top-10.\n",
                   md_table(pl), ""]
        lg = pd.read_csv(sp / "life_group_analysis.csv")
        report += ["SHAP by life group (final ensemble):\n", md_table(lg.drop(columns=["edges_from_train"]).round(1)), ""]
        lc = pd.read_csv(sp / "local_explanations.csv")
        report += ["Local explanations:\n", md_table(lc.round(1)), ""]

    (res / "REPORT.md").write_text("\n".join(report), encoding="utf-8")
    print(f"wrote {res / 'REPORT.md'}")


if __name__ == "__main__":
    main()
